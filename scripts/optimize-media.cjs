/** Offline, reproducible asset preparation using the existing Playwright Chrome. */
const fs = require('node:fs');
const path = require('node:path');
const crypto = require('node:crypto');
const sizeOf = require('image-size');
const { chromium } = require('@playwright/test');

const root = path.resolve(__dirname, '..');
const references = new Set();
function scan(directory) {
  for (const entry of fs.readdirSync(directory, { withFileTypes: true })) {
    const file = path.join(directory, entry.name);
    if (entry.isDirectory()) scan(file);
    else if (entry.name.endsWith('.html')) {
      const html = fs.readFileSync(file, 'utf8');
      for (const match of html.matchAll(/\b(?:data-media-)?src\s*=\s*["'](\/?assets\/[^"']+)["']/g)) {
        if (/\.(jpe?g|png|webp|svg)$/i.test(match[1])) references.add(match[1].replace(/^\//, ''));
      }
    }
  }
}

async function main() {
  scan(path.join(root, 'src/app'));
  const manifest = {};
  const report = [];
  const missingSources = [];
  for (const src of [...references].sort()) {
    const file = path.join(root, 'src', src);
    if (!fs.existsSync(file)) { missingSources.push(src); continue; }
    let dimensions;
    try { dimensions = sizeOf(file); } catch { continue; }
    manifest[src] = { width: dimensions.width, height: dimensions.height };
    report.push({ src, bytes: fs.statSync(file).size, ...manifest[src] });
  }
  if (process.argv.includes('--audit')) {
    console.log(JSON.stringify({ count: report.length, bytes: report.reduce((n, item) => n + item.bytes, 0), candidates: report.filter(item => item.bytes > 120 * 1024).length, missingSources, largest: [...report].sort((a, b) => b.bytes - a.bytes).slice(0, 15) }, null, 2));
    return;
  }
  const output = path.join(root, 'src/assets/optimized-media');
  fs.mkdirSync(output, { recursive: true });
  const writeManifest = () => fs.writeFileSync(path.join(root, 'src/app/shared/media-manifest.ts'), '// Generated by node scripts/optimize-media.cjs. Original assets are preserved.\nexport interface MediaMetadata { readonly width: number; readonly height: number; readonly src?: string; readonly srcset?: string; }\nexport const MEDIA_MANIFEST: Readonly<Record<string, MediaMetadata>> = ' + JSON.stringify(manifest, null, 2) + ';\n');
  if (process.argv.includes('--metadata-only')) {
    const existing = fs.readFileSync(path.join(root, 'src/app/shared/media-manifest.ts'), 'utf8');
    const previous = JSON.parse(existing.slice(existing.indexOf(' = {') + 3).replace(/;\s*$/, ''));
    const previousReport = JSON.parse(fs.readFileSync(path.join(root, 'reports/image-performance.json'), 'utf8'));
    const previousImages = new Map(previousReport.images.map(item => [item.src, item]));
    for (const item of report) {
      if (previous[item.src]) manifest[item.src] = { ...previous[item.src], ...manifest[item.src] };
      Object.assign(item, previousImages.get(item.src) || { optimizedBytes: item.bytes });
    }
    writeManifest();
    writeReport(report, missingSources);
    console.log(`Refreshed ${report.length} metadata records without re-encoding images.`);
    return;
  }
  writeManifest();
  const browser = await chromium.launch({ channel: 'chrome', headless: true });
  try {
    const page = await browser.newPage();
    for (const item of report) {
      item.optimizedBytes = item.bytes;
      if (item.bytes <= 120 * 1024 || /\.svg$/i.test(item.src)) continue;
      const file = path.join(root, 'src', item.src);
      const mime = /\.png$/i.test(item.src) ? 'image/png' : /\.webp$/i.test(item.src) ? 'image/webp' : 'image/jpeg';
      const data = `data:${mime};base64,${fs.readFileSync(file).toString('base64')}`;
      const hash = crypto.createHash('sha256').update(item.src).digest('hex').slice(0, 12);
      const variants = [];
      for (const target of [900, 1800]) {
        const width = Math.min(item.width, target);
        if (variants.some(variant => variant.width === width)) continue;
        const result = await page.evaluate(async ({ data, width }) => {
          const image = new Image();
          image.src = data;
          await image.decode();
          const canvas = document.createElement('canvas');
          canvas.width = width;
          canvas.height = Math.round(image.naturalHeight * width / image.naturalWidth);
          const context = canvas.getContext('2d');
          context.imageSmoothingQuality = 'high';
          context.drawImage(image, 0, 0, canvas.width, canvas.height);
          return { data: canvas.toDataURL('image/webp', 0.9).split(',')[1], height: canvas.height };
        }, { data, width });
        const buffer = Buffer.from(result.data, 'base64');
        if (buffer.length >= item.bytes) continue;
        const name = `${hash}-${width}.webp`;
        fs.writeFileSync(path.join(output, name), buffer);
        variants.push({ src: `assets/optimized-media/${name}`, width, height: result.height, bytes: buffer.length });
      }
      const main = variants.at(-1);
      if (main) {
        // A smaller mobile candidate must never replace a sharper original on desktop.
        const fullSize = main.width === Math.min(item.width, 1800);
        if (fullSize) manifest[item.src].src = main.src;
        const candidates = variants.map(variant => `${variant.src} ${variant.width}w`);
        if (!fullSize) candidates.push(`${item.src} ${item.width}w`);
        if (candidates.length > 1) manifest[item.src].srcset = candidates.join(', ');
        item.optimizedBytes = fullSize ? main.bytes : item.bytes;
        item.variants = variants;
      }
    }
  } finally {
    await browser.close();
  }
  const summary = writeReport(report, missingSources);
  writeManifest();
  console.log(JSON.stringify({ imageCount: summary.imageCount, originalBytes: summary.originalBytes, optimizedBytes: summary.optimizedBytes, savedBytes: summary.originalBytes - summary.optimizedBytes }));
}
function writeReport(report, missingSources) {
  const summary = { imageCount: report.length, originalBytes: report.reduce((n, item) => n + item.bytes, 0), optimizedBytes: report.reduce((n, item) => n + item.optimizedBytes, 0), mobileBytes: report.reduce((n, item) => n + (item.variants?.[0]?.bytes ?? item.bytes), 0), generatedBytes: report.reduce((n, item) => n + (item.variants || []).reduce((bytes, variant) => bytes + variant.bytes, 0), 0), missingSources, images: report };
  fs.mkdirSync(path.join(root, 'reports'), { recursive: true });
  fs.writeFileSync(path.join(root, 'reports/image-performance.json'), JSON.stringify(summary, null, 2) + '\n');
  return summary;
}
main().catch(error => { console.error(error); process.exitCode = 1; });
